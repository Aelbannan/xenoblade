#pragma inline_max_size(10000)
#pragma inline_max_total_size(10000)
static __inline void __VISetMacrovisionTable(u8* pt) {
    u8 buf[0x1B];
    u8* d = buf;
    s32 i;

    *d++ = 0x40;
    for (i = 0; i < 0x1A; i++) {
        *d++ = *pt++;
    }
    __VISendI2CData(0xE0, buf, 0x1B);
    WaitMicroTime(2);
}

void __VISetMacrovision(void) {
    u8* base = (u8*)gammaSet;

    switch (__type) {
    case VI_ACP_TYPE1:
        switch (__tvType) {
        case 0:
            __VISetMacrovisionTable(base + 0x420);
            break;
        case 1:
            __VISetMacrovisionTable(base + 0x474);
            break;
        case 2:
            __VISetMacrovisionTable(base + 0x51C);
            break;
        case 5:
            __VISetMacrovisionTable(base + 0x4C8);
            break;
        default:
            break;
        }
        break;
    case VI_ACP_TYPE2:
        switch (__tvType) {
        case 0:
            __VISetMacrovisionTable(base + 0x43C);
            break;
        case 1:
            __VISetMacrovisionTable(base + 0x490);
            break;
        case 2:
            __VISetMacrovisionTable(base + 0x538);
            break;
        case 5:
            __VISetMacrovisionTable(base + 0x4E4);
            break;
        default:
            break;
        }
        break;
    case VI_ACP_TYPE3:
        switch (__tvType) {
        case 0:
            __VISetMacrovisionTable(base + 0x458);
            break;
        case 1:
            __VISetMacrovisionTable(base + 0x4AC);
            break;
        case 2:
            __VISetMacrovisionTable(base + 0x554);
            break;
        case 5:
            __VISetMacrovisionTable(base + 0x500);
            break;
        default:
            break;
        }
        break;
    case VI_ACP_OFF:
        __VISetMacrovisionTable(VIZeroACPType);
        break;
    default:
        break;
    }
}

void __VISetGammaImm(VIGammaObj* gamma) {
    u8 buf[0x22];
    u16* p;

    buf[0] = 0x10;
    p = (u16*)gamma;
    buf[2] = (u8)p[0];
    buf[1] = (p[0] >> 8) & 0xFF;
    buf[4] = (u8)p[1];
    buf[3] = (p[1] >> 8) & 0xFF;
    buf[6] = (u8)p[2];
    buf[5] = (p[2] >> 8) & 0xFF;
    buf[8] = (u8)p[3];
    buf[7] = (p[3] >> 8) & 0xFF;
    buf[10] = (u8)p[4];
    buf[9] = (p[4] >> 8) & 0xFF;
    buf[12] = (u8)p[5];
    buf[11] = (p[5] >> 8) & 0xFF;
    buf[13] = gamma->yin[0];
    buf[14] = gamma->yin[1];
    buf[15] = gamma->yin[2];
    buf[16] = gamma->yin[3];
    buf[17] = gamma->yin[4];
    buf[18] = gamma->yin[5];
    buf[19] = gamma->yin[6];
    buf[20] = (p[10] >> 8) & 0xFF;
    buf[21] = p[10] & 0xC0;
    buf[22] = (p[11] >> 8) & 0xFF;
    buf[23] = p[11] & 0xC0;
    buf[24] = (p[12] >> 8) & 0xFF;
    buf[25] = p[12] & 0xC0;
    buf[26] = (p[13] >> 8) & 0xFF;
    buf[27] = p[13] & 0xC0;
    buf[28] = (p[14] >> 8) & 0xFF;
    buf[29] = p[14] & 0xC0;
    buf[30] = (p[15] >> 8) & 0xFF;
    buf[31] = p[15] & 0xC0;
    buf[32] = (p[16] >> 8) & 0xFF;
    buf[33] = p[16] & 0xC0;

    __VISendI2CData(0xE0, buf, 0x22);
    WaitMicroTime(2);
}

void __VISetGamma1_0(void) {
    __VISetGammaImm((VIGammaObj*)(gammaSet + 0x154));
}

void __VISetGamma(void) {
    __VISetGammaImm((VIGammaObj*)(gammaSet + (u32)__gamma * 0x22));
}

void VISetGamma(VIGamma gamma) {
    if (__gamma == gamma) {
        return;
    }
    __gamma = gamma;
    Vdac_Flag_Changed |= 0x10;
}

void __VISetTrapFilter(void) {
    u8 buf[2];

    buf[0] = 3;
    if (__filter == 1) {
        buf[1] = 0;
    } else {
        buf[1] = 1;
    }
    __VISendI2CData(0xE0, buf, 2);
    WaitMicroTime(2);
}

void VISetTrapFilter(VIBool filter) {
    if ((u32)__filter == (u32)filter) {
        return;
    }
    __filter = filter;
    Vdac_Flag_Changed |= 0x20;
}

void __VISetRGBOverDrive(void) {
    u8 buf[2];

    if (Vdac_Flag_Region == 3) {
        buf[0] = 0xA;
        buf[1] = (__level << 1) | 1;
        __VISendI2CData(0xE0, buf, 2);
        WaitMicroTime(2);
    } else {
        buf[0] = 0xA;
        buf[1] = 0;
        __VISendI2CData(0xE0, buf, 2);
        WaitMicroTime(2);
    }
}

void VISetRGBModeImm(void) {
    Vdac_Flag_Changed |= 0x80;
}

void __VISetRGBModeImm(void) {
    u8 buf[2];

    Vdac_Flag_Region = 3;
    buf[0] = 1;
    buf[1] = 3;
    __VISendI2CData(0xE0, buf, 2);
    WaitMicroTime(2);
}

void __VISetRevolutionModeSimple(void) {
    s32 region;
    u32 tvFormat;
    u32 dtvStatus;
    u8 bufA[2];
    u8 bufB[2];
    u8 bufC[2];
    u8 bufD[2];
    u8 bufE[3];
    u8 bufF[2];
    u8 bufG[3];
    u8 bufH[3];
    u8 bufI[5];
    u8 bufJ[0x1B];
    u8 bufK[2];
    u8 bufL[2];

    region = 1;

    bufA[0] = 0x6A;
    bufA[1] = 0x01;
    __VISendI2CData(0xE0, bufA, 2);
    WaitMicroTime(2);

    bufB[0] = 0x65;
    bufB[1] = 0x01;
    __VISendI2CData(0xE0, bufB, 2);
    WaitMicroTime(2);

    dtvStatus = VIGetDTVStatus();
    tvFormat = *(volatile u32*)0x800000CC;
    switch (tvFormat) {
    case 1:
    case 5:
        region = 2;
        Vdac_Flag_Region = 2;
        break;
    case 2:
        Vdac_Flag_Region = 1;
        break;
    case 0:
        region = 0;
        Vdac_Flag_Region = 0;
        break;
    default:
        region = 0;
        Vdac_Flag_Region = 0;
        break;
    }

    bufC[0] = 1;
    bufC[1] = (u8)dtvStatus << 5 | (u8)region;
    __VISendI2CData(0xE0, bufC, 2);
    WaitMicroTime(2);

    bufD[0] = 0;
    bufD[1] = 0;
    __VISendI2CData(0xE0, bufD, 2);
    WaitMicroTime(2);

    bufE[0] = 0x71;
    bufE[1] = 0x8E;
    bufE[2] = 0x8E;
    __VISendI2CData(0xE0, bufE, 3);
    WaitMicroTime(2);

    bufF[0] = 2;
    bufF[1] = 7;
    __VISendI2CData(0xE0, bufF, 2);
    WaitMicroTime(2);

    __wd0 = 0;
    __wd1 = 0;
    __wd2 = 0;
    bufG[0] = 5;
    bufG[1] = 0;
    bufG[2] = 0;
    __VISendI2CData(0xE0, bufG, 3);
    WaitMicroTime(2);

    if (__gp1 != 0 || __gp2 != 0 || __gp3 != 0 || __gp4 != 0) {
        u32 flag = Vdac_Flag_Changed | 0x2;
        __gp1 = 0;
        __gp2 = 0;
        __gp3 = 0;
        __gp4 = 0;
        Vdac_Flag_Changed = flag;
    }

    bufH[0] = 8;
    bufH[1] = __gp1 & 0xF;
    bufH[1] |= (__gp2 & 0xF) << 4;
    bufH[2] = __gp3 & 7;
    bufH[2] |= (__gp4 & 7) << 3;
    __VISendI2CData(0xE0, bufH, 3);
    WaitMicroTime(2);

    if (__cc1 != 0 || __cc2 != 0 || __cc3 != 0 || __cc4 != 0) {
        u32 flag = Vdac_Flag_Changed | 0x4;
        __cc1 = 0;
        __cc2 = 0;
        __cc3 = 0;
        __cc4 = 0;
        Vdac_Flag_Changed = flag;
    }

    bufI[0] = 0x7A;
    bufI[1] = __cc1 & 0x7F;
    bufI[2] = __cc2 & 0x7F;
    bufI[3] = __cc3 & 0x7F;
    bufI[4] = __cc4 & 0x7F;
    __VISendI2CData(0xE0, bufI, 5);
    WaitMicroTime(2);

    __VISetMacrovisionTable(VIZeroACPType);

    if (__level != 0) {
        __level = 0;
        Vdac_Flag_Changed |= 0x40;
    }

    if (Vdac_Flag_Region == 3) {
        bufK[0] = 0xA;
        bufK[1] = (__level << 1) | 1;
        __VISendI2CData(0xE0, bufK, 2);
        WaitMicroTime(2);
    } else {
        bufK[0] = 0xA;
        bufK[1] = 0;
        __VISendI2CData(0xE0, bufK, 2);
        WaitMicroTime(2);
    }

    bufL[0] = 3;
    bufL[1] = 1;
    __VISendI2CData(0xE0, bufL, 2);
    WaitMicroTime(2);

    __VISetGammaImm((VIGammaObj*)(gammaSet + 0x154));
    __current_3in1_video_mode = 0;
}
