f32 FExpLn2(f32 x) {
    f32 fidx = (16 / NW4R_MATH_LN_2) * (NW4R_MATH_LN_2 + x);
    u16 whole = F32ToU16(fidx);
    f32 frac = fidx - U16ToF32(whole);

    return reinterpret_cast<const ExpSample*>(lbl_eu_80569CD0)[whole].exp_val + frac * reinterpret_cast<const ExpSample*>(lbl_eu_80569CD0)[whole].exp_delta;
}

f32 FLog1_2(f32 x) {
    f32 fidx = 256.0f * (x - 1.0f);
    u16 whole = F32ToU16(fidx);
    f32 frac = fidx - U16ToF32(whole);

    return reinterpret_cast<const LogSample*>(lbl_eu_80569DD8)[whole].log_val + frac * reinterpret_cast<const LogSample*>(lbl_eu_80569DD8)[whole].log_delta;
}

