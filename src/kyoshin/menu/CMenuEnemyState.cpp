void CMenuEnemyState::cbRenderBefore() {
    CTaskGame::getInstance();
    if (CTaskGame::isFlag01Set()) {
        goto done;
    }
    if ((gmPauseFlags & (1u << 21)) != 0) {
        goto done;
    }
    if (!IsMenuState621F0()) {
        goto done;
    }
    if (gmGameFlags & 0xAFA40000u) {
        goto done;
    }

    {
        GXSetZMode(GX_FALSE, GX_NEVER, GX_FALSE);
        nw4r::lyt::DrawInfo drawInfo;
        SetWideLocAdjust(&drawInfo);

        u32 indices[0x18];
        u8 fill;
        for (fill = 0; fill < 0x18; fill++) {
            indices[fill] = fill;
        }

        // Outer for(left!=0) -> mtctr/bdnz. Inner bottom-tested goto keeps CTR outer.
        // Rematerialize &indices[j] each step (retail addi r1,0x8). Load depthB before
        // depthA so fcmpo uses f1/f0. XOR via store-reload of order[j]/pair[1].
        {
            // pass-before-order + block-scoped limit -> order=r9, j=r12, swapped=r11
            // (retail). Peak 99.172%: pass/limit/pair still color r8/r10/r30 vs
            // retail r10/r5/r8; XOR operand/dest Chaitin follows from that.
            // Decl order pins colors: order=r9, pass=r10, limit=r5, left=CTR;
            // pair rematerializes into the freed r8 each step.
            // No alias pointer here: retail caches the bare array base in a
            // register for indexed x[j] accesses while j+1 accesses go through
            // a recomputed element address.
            u8 pass = 0;
            u32 left;
            for (left = 0x17; left != 0; left--) {
                u8 swapped = 0;
                u8 j = 0;
                goto sort_test;
            sort_body: {
                    u32 idxA = indices[j];
                    u32 idxB = indices[j + 1];
                    if (panels[idxA].animMarker > panels[idxB].animMarker) {
                        // Source-level XOR swap; retail interleaves the flag
                        // store after the first assignment.
                        indices[j] ^= indices[j + 1];
                        swapped = 1;
                        indices[j + 1] ^= indices[j];
                        indices[j] ^= indices[j + 1];
                    }
                    j++;
                }
            sort_test:
                if ((s32)j < 0x17 - (s32)pass) {
                    goto sort_body;
                }
                if (swapped == 0) {
                    break;
                }
                pass++;
            }
        }

        // NV decl order entry, order, i -> r30/r29/r28 (MWCC_CASES 8c6).
        // u32 counter; cast to u8 only when indexing. Compare stays cmpli (no
        // terminal clrlwi) so .text is retail 0x274.
        // Declare order before i so saved-reg claim gives order=r29, i=r28
        // (docs/register_mapping.md Rule A / mwcc-wii-1.1 claim descending).
        {
            u32* order;
            u32 i;
            order = indices;
            i = 0;
            do {
                MenuEnemyPanel& p = panels[order[static_cast<u8>(i)]];
                if (p.visible == 0) {
                    goto draw_next;
                }
                if (p.unk29 == 0) {
                    goto draw_next;
                }
                if (p.panelType != 0) {
                    drawLayout(unk74, &drawInfo, 0, 1);
                }
                {
                    int drawFlag = (p.panelType == 0) ? 0 : 1;
                    drawFlag = (drawFlag == 0) ? 1 : 0;
                    drawLayout(p.layout2, &drawInfo, drawFlag, 1);
                }
                if (p.drawLayout0Flag == 0) {
                    drawLayout(p.layout1, &drawInfo, 0, 1);
                }
            draw_next:
                i++;
            } while (i < 0x18);
        }

        if (selectCursor.field44 != 0) {
            drawLayout(selectCursor.layout1C, &drawInfo, 0, 1);
        }
    }
done:
    ;
}

void CMenuEnemyState::Move() {
    CTaskGame::getInstance();
    if (CTaskGame::isFlag01Set()) {
        goto done;
    }
    if ((gmPauseFlags & (1u << 21)) != 0) {
        goto done;
    }
    if (!IsMenuState621F0()) {
        goto done;
    }
    if (gmGameFlags & 0xAFA40000u) {
        goto done;
    }
    if (isSceneActive__Q22cf13CfGameManagerFv()) {
        goto done;
    }

    {
    // Pulse / target-highlight setup. All failure paths jump straight to the
    // consume point (targetDone) like retail, so obj's live range ends exactly
    // where noTarget = 0 is written and MWCC coalesces them into one register.
    {
        int noTarget = 1;

        if (cf::CfGameManager::getPlayer(0) != NULL) {
            // Reading offset 0x90E4 from Selector_GetInstance().
            u32 lastId = *reinterpret_cast<u32*>(
                reinterpret_cast<u8*>(Selector_GetInstance()) + 0x90E4);

            if (lastId != 0) {
                Obj64_91* obj = reinterpret_cast<Obj64_91*>(findObjectById(static_cast<int>(lastId)));

                if (obj == NULL) {
                    goto targetDone;
                }
                // Bool-store form reproduces retail's rlwinm/cntlzw/srwi chain.
                bool active = (obj->word64 >> 2) & 1;
                if (!active) {
                    goto targetDone;
                }
                {
                        if (unk834 != 0) {
                            f32 v = unk838 - (sdata2_MESPool.f0C);
                            unk838 = v;
                            if (v <= (sdata2_MESPool.f04)) {
                                unk838 = (sdata2_MESPool.f04);
                            }
                        } else {
                            f32 v = unk838 + (sdata2_MESPool.f0C);
                            unk838 = v;
                            if (v >= (sdata2_MESPool.fE8)) {
                                unk838 = (sdata2_MESPool.fE8);
                                unk834 = 1;
                            }
                        }

                        if (lastId != unk830) {
                            unk834 = 0;
                            unk838 = (sdata2_MESPool.f04);

                            void* oldObj = findObjectById(static_cast<int>(unk830));
                            // Double guard matches retail's paired beq before the call.
                            if (oldObj != NULL) {
                                if (oldObj != NULL) {
                                    CfModel_NotifyReady(oldObj);
                                }
                            }
                            unk830 = lastId;
                        }

                        if (!sEnemyMenuOnceFlag) {
                            sEnemyMenuOnceFlag = 1;
                        }

                        {
                            f32 t = ml::pi * unk838;
                            t = (sdata2_MESPool.f10) * t;
                            f32 s = nw4r::math::SinFIdx(t);
                            sEnemyPulseVector[0] = s;
                            sEnemyPulseVector[1] = s;
                            sEnemyPulseVector[2] = (sdata2_MESPool.fE8);
                            CfModel_GetSpeedRate(obj, sEnemyPulseVector);
                        }

                        noTarget = 0;
                }
            }
        }
    targetDone:
        ;
        if (noTarget) {
            if (unk830 != 0) {
                void* h = findObjectById(static_cast<int>(unk830));
                if (h != NULL) {
                    if (h != NULL) {
                        CfModel_NotifyReady(h);
                    }
                }
                unk830 = 0;
            }
        }
    }

    this->EneSt_RefreshMenu();

    // Retail pre-loop materialization (80110A88..AA4): pc call, then
    // f30/r30/f31/r29/f28/r28/r27/r31 - declare in that dependence order.
    cf::CfObjectPc* pc =
        getCfObjectPc(cf::CfGameManager::getPlayer(0));
    f32 animMarker = sEnemyPanelAnimMarker;
    f32 distThresh = (sdata2_MESPool.f14);
    nw4r::math::VEC3 scratch;
    nw4r::math::VEC3* pScratch = &scratch;
    f32 one = (sdata2_MESPool.fE8);
    nw4r::math::VEC3 delta;
    nw4r::math::VEC3* pDelta = &delta;
    u8 i = 0;
    u8 z = 0;

    for (; i < 0x18; i++) {
        MenuEnemyPanel& panel = panels[i];

        if (panel.visible == 0) {
            continue;
        }

        if (panel.panelType == 0) {
            if (GetSysStateFlag23()) {
                u8& b1 = static_cast<ObjBBFlag*>(panel.obj1)->flagBB;
                u8& b2 = static_cast<ObjBBFlag*>(panel.obj2)->flagBB;
                u8& b3 = static_cast<ObjBBFlag*>(panel.obj3)->flagBB;
                b1 = (b1 & 0xFE) | 1;
                b2 = (b2 & 0xFE) | 1;
                b3 = (b3 & 0xFE) | 1;
            }
        }

        u32 actorId = panel.actorId;
        Obj64_91* handle = reinterpret_cast<Obj64_91*>(findObjectById(static_cast<int>(actorId)));
        if (handle == NULL) {
            panel.visible = z;
            continue;
        }

        // r24 in retail's loop = result of MapFx_ResolveOwner (not the early target).
        Actor2Layout* actor2 = reinterpret_cast<Actor2Layout*>(MapFx_ResolveOwner(NULL));
        int skipDist = 0;
        int hasSub = 0;
        if (actor2 != NULL) {
            Sub3F34Layout* sub3f34 = actor2->sub3F34;
            if (sub3f34 != NULL) {
                hasSub = 1;
            }
        }
        if (hasSub) {
            Sub3F34Layout* sub3f34 = actor2->sub3F34;
            u32 bits = sub3f34->bits7A4;
            if ((bits >> 26) & 1) {
                skipDist = 1;
            }
        }

        if (actor2 != NULL) {
            f32 stateVal = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getHp();
            // Retail: state==FEC && panelData[0x1c]==0 -> always cull.
            if (animMarker == stateVal) {
                if (panel.unk1C == 0) {
                    panel.visible = z;
                    continue;
                }
            }
        }
        if (skipDist) {
            panel.visible = z;
            continue;
        }

        // Distance cull + frustum test only when panelType==0 and pc!=NULL.
        // Retail skips both when either gate fails (falls through to flag work).
        if (panel.panelType == 0 && pc != NULL) {
            ml::CVec3* handlePos = reinterpret_cast<cf::CfObject*>(handle)->CfObject_getPosVector();
            PcEmbedLayout* pcEmbed = reinterpret_cast<PcEmbedLayout*>(pc);
            ml::CVec3* pcPos = reinterpret_cast<cf::CfObject*>(pcEmbed)->CfObject_getPosVector();

            nw4r::math::VEC3Sub(
                pDelta,
                reinterpret_cast<const nw4r::math::VEC3*>(pcPos),
                reinterpret_cast<const nw4r::math::VEC3*>(handlePos));
            scratch = delta;
            // Retail: interleaved assign + VEC3LenSq (ps_mul/ps_madd/ps_sum0).
            f32 distSq = nw4r::math::VEC3LenSq(pScratch);
            if (distSq > distThresh) {
                panel.visible = z;
                continue;
            }

            {
                PoseLayout* pose = static_cast<PoseLayout*>(Scn_FindCamItem(unk60, -1));
                Vec3f a;
                a.x = pose->vec10c_x;
                a.y = pose->vec10c_y;
                a.z = pose->vec10c_z;
                Vec3f b;
                b.x = pose->vec138_x;
                b.y = pose->vec138_y;
                b.z = pose->vec138_z;

                ml::CVec3* qpos = reinterpret_cast<cf::CfObject*>(handle)->CfObject_getPosVector();
                Vec3f c = *reinterpret_cast<const Vec3f*>(qpos);

                if (!CheckViewAngle60((const nw4r::math::VEC3*)&a, (const nw4r::math::VEC3*)&b, (const nw4r::math::VEC3*)&c)) {
                    panel.visible = z;
                    continue;
                }
            }
        }

        if (panel.panelType == 0) {
            if (panel.unk1D != 0) {
                if (actor2 != NULL) {
                    u8& b1 = static_cast<ObjBBFlag*>(panel.obj1)->flagBB;
                    u8& b2 = static_cast<ObjBBFlag*>(panel.obj2)->flagBB;
                    u8& b3 = static_cast<ObjBBFlag*>(panel.obj3)->flagBB;

                    b1 = (b1 & 0xFE) | 1;
                    b2 = b2 & 0xFE;

                    u32* r = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getMarkKindPtr();
                    u32 v = *r;
                    if (v - 1 <= 3) {
                        b2 = (b2 & 0xFE) | 1;
                    }

                    u32 byteVal = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_isMarkVisible() & 0xFF;
                    b3 = (b3 & 0xFE) | static_cast<u8>(byteVal);
                }
            } else {
                u8& b1 = static_cast<ObjBBFlag*>(panel.obj1)->flagBB;
                u8& b2 = static_cast<ObjBBFlag*>(panel.obj2)->flagBB;
                u8& b3 = static_cast<ObjBBFlag*>(panel.obj3)->flagBB;
                b1 = b1 & 0xFE;
                b2 = b2 & 0xFE;
                b3 = b3 & 0xFE;
            }
        }

        this->EneSt_UpdatePanelHighlight(reinterpret_cast<u8*>(&panel));

        {
            Vec3f posTmp;
            Vec3f posA;
            Vec3f posB;
            Vec3f* posTmpPtr = &posTmp;

            void* rRaw = reinterpret_cast<cf::CfObject*>(handle)->CfObject_getPosSample(0x64);
            RLayout* r = static_cast<RLayout*>(rRaw);
            if (r != NULL) {
                posTmpPtr->x = r->val0C;
                posTmpPtr->y = r->val1C;
                posTmpPtr->z = r->val2C;
                posA = *posTmpPtr;
            } else {
                ml::CVec3* p = reinterpret_cast<cf::CfObject*>(handle)->CfObject_getPosVector();
                posA = *reinterpret_cast<const Vec3f*>(p);
            }

            ml::CVec3* p2 = reinterpret_cast<cf::CfObject*>(handle)->CfObject_getPosVector();
            posB = *reinterpret_cast<const Vec3f*>(p2);

            Obj64_91* hf = handle;
            u32 flagWord = hf->word64;
            // Bit-extract-to-bool forms reproduce retail's rlwinm/cntlzw pairs.
            bool flag14 = (flagWord >> 14) & 1;
            bool flag15 = (flagWord >> 15) & 1;
            if (flag14 || flag15) {
                if (handle != NULL) {
                    u8 animState = hf->byte91;
                    if (animState == 6) {
                        posA.y += one;
                    }
                }
            }

            this->EneSt_PositionPanel(reinterpret_cast<u8*>(&panel), &posA, &posB);
        }

        if (panel.unk1F == 0 && actor2 != NULL) {
            this->EneSt_RefreshNameColor(reinterpret_cast<u8*>(&panel));

            if (panel.unk1C != 0) {
                u32 count = cf::CBattleManager::getInstance()->mActorList1.size();
                panel.drawLayout0Flag = (count == 0) ? 1 : 0;
            } else {
                void* subObj = actor2->subObj4;
                void* resultRaw = reinterpret_cast<cf::CObjectState*>(subObj)->getStateData();
                int* result = static_cast<int*>(resultRaw);
                int localVal = *result;
                u32 ret = testActorStatus(actor2, &localVal, 0x803);
                panel.drawLayout0Flag = (ret == 0) ? 1 : 0;
            }

            if (panel.drawLayout0Flag == 0) {
                f32 v12c = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getDamageScale();
                f32 v128 = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getHp();
                EneSt_ScalePaneWidths(this, reinterpret_cast<u8*>(&panel), v128, v12c);

                v12c = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getDamageScale();
                v128 = reinterpret_cast<cf::CActorParam*>(actor2)->CActorParam_getHp();
                EneSt_UpdateIndicator(this, reinterpret_cast<u8*>(&panel), v128, v12c);

                EneSt_SearchHighlightTexture(this, reinterpret_cast<u8*>(&panel), actor2);
            }
        }

        if (panel.panelType != 0) {
            u8& b1 = static_cast<ObjBBFlag*>(panel.obj1)->flagBB;
            u8& b2 = static_cast<ObjBBFlag*>(panel.obj2)->flagBB;
            u8& b3 = static_cast<ObjBBFlag*>(panel.obj3)->flagBB;
            b1 = b1 & 0xFE;
            b2 = b2 & 0xFE;
            b3 = b3 & 0xFE;
        } else if (!GetSysStateFlag23()) {
            u8& b1 = static_cast<ObjBBFlag*>(panel.obj1)->flagBB;
            u8& b2 = static_cast<ObjBBFlag*>(panel.obj2)->flagBB;
            u8& b3 = static_cast<ObjBBFlag*>(panel.obj3)->flagBB;
            b1 = b1 & 0xFE;
            b2 = b2 & 0xFE;
            b3 = b3 & 0xFE;
        }
    }

    if (panels[23].visible != 0) {
        // Countdown form so MWCC puts the trip count in CTR (retail bdnz).
        s32 left = 0x17;
        u32 j = 0;
        for (;;) {
            MenuEnemyPanel& panel2 = panels[j];
            if (panel2.visible != 0) {
                if (panel2.actorId == panels[23].actorId) {
                    panel2.visible = z;
                    break;
                }
            }
            j++;
            if (--left == 0) {
                break;
            }
        }
    }

    advanceAnimTransform(unk78, (sdata2_MESPool.fE8));
    unk74->Animate(0);

    switch (selectCursor.field44) {
    case 1:
        if (advanceAnimTransform(selectCursor.anim20, (sdata2_MESPool.fE8)) != 0) {
            selectCursor.byte40 = 1;
            selectCursor.field44 = 2;
        }
        break;
    case 3:
        if (AnimRewindFrame(selectCursor.anim20, (sdata2_MESPool.fE8)) != 0) {
            selectCursor.byte40 = 1;
            selectCursor.field44 = 0;
        }
        break;
    case 4:
        if (advanceAnimTransform(selectCursor.anim24, (sdata2_MESPool.fE8)) != 0) {
            reinterpret_cast<AnimTransformOverlay*>(selectCursor.anim24)->field10 = sEnemyPanelAnimMarker;
            selectCursor.layout1C->Animate(0);
            selectCursor.layout1C->SetAnimationEnable(selectCursor.anim24, false);
            selectCursor.layout1C->SetAnimationEnable(selectCursor.anim20, true);
            selectCursor.field44 = 3;
        }
        break;
    default:
        break;
    }

    if (selectCursor.field44 != 0) {
        selectCursor.EneSt_CursorUpdate();
    }

    selectCursor.layout1C->Animate(0);
    }
done:
    ;
}

// EneSt_CursorBuild (us-8010f620): CPcSelectCursor layout/anim init. Creates a
// 0x2000 scratch region, builds the layout + two anims from the shared arc
// accessor (field18), grabs six named panes off the root pane, then enables
// anim20. Called after the ctor from the owning menu's file-event path.
void CPcSelectCursor::EneSt_CursorBuild() {
    this->mem08.createRegion(mtl::MemManager::getHandleMEM2(), 0x2000,
                             &sMenuEnemyNamePool[0x00], 0);
    Class_8045F858 regionGuard(&this->mem08);
    mtl::MemManager::setMemInitFlag(false);

    // Retail reloads field18 (the arc accessor) and layout1C per call instead
    // of caching them in locals, so each is re-loaded from the object.
    buildLayout(&this->layout1C,
                  reinterpret_cast<nw4r::lyt::ArcResourceAccessor*>(this->field18),
                  &sMenuEnemyNamePool[0x10]);
    bindLayoutAnimTransform(this->layout1C, &this->anim20,
                  reinterpret_cast<nw4r::lyt::ArcResourceAccessor*>(this->field18),
                  &sMenuEnemyNamePool[0x2c]);
    bindLayoutAnimTransform(this->layout1C, &this->anim24,
                  reinterpret_cast<nw4r::lyt::ArcResourceAccessor*>(this->field18),
                  &sMenuEnemyNamePool[0x4b]);

    this->field28 = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x6a], true);
    this->field34 = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x72], true);
    this->field2C = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x7c], true);
    this->field30 = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x86], true);
    this->field38 = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x90], true);
    this->field3C = (u32)this->layout1C->GetRootPane()->FindPaneByName(
        &sMenuEnemyNamePool[0x9c], true);

    this->layout1C->SetAnimationEnable(this->anim24, false);
    this->layout1C->SetAnimationEnable(this->anim20, true);
    this->layout1C->Animate(0);
}

