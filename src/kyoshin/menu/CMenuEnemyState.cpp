    if (tex != NULL) {
        PaneSetTexPalette((nw4r::lyt::Pane*)panel->obj2, (TPLPalette*)tex);
        reinterpret_cast<ObjBBFlag*>(panel->obj2)->flagBB |= 1;
    }

