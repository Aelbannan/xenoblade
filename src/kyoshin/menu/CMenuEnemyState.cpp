    self->EneSt_HighlightPane(panelData, 3);
    reinterpret_cast<ObjBBFlag*>(paneE7)->flagBB =
        (reinterpret_cast<ObjBBFlag*>(paneE7)->flagBB & 0xFE) | 1;

